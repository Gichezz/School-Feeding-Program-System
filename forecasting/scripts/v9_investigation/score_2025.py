"""
Protocol version 9, part A (config/anomaly_v9.yaml): version 8 run as deployed over 2025,
the development year, keeping what the investigation needs: every school-day's score and
every school-week's weekly score, rank, review threshold and whether it was listed.

The loop is version 8's (scripts/run_anomaly_v8.py, final setting), stopped at the end of
2025, so nothing from 2026 is scored or read.

Output (not committed; regenerated by this script)
  data/processed/feeding_deployment/v9_investigation/days_2025.csv.gz
  data/processed/feeding_deployment/v9_investigation/weeks_2025.csv.gz
"""

import copy
import json
import os
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
FORECASTING_DIR = HERE.parent.parent
sys.path.insert(0, str(FORECASTING_DIR))
sys.path.insert(0, str(FORECASTING_DIR / "scripts"))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import yaml  # noqa: E402

from anomaly.methods import METHODS  # noqa: E402
from anomaly.weekly import weekly_scores  # noqa: E402
from generate_feeding_dataset import OUT_DIR as MAIN_DATA, generate  # noqa: E402
import run_anomaly_deployment_test as v7  # noqa: E402
import run_anomaly_v8 as v8  # noqa: E402

OUT = FORECASTING_DIR / "data" / "processed" / "feeding_deployment" / "v9_investigation"
END_2025 = pd.Timestamp("2025-12-31")
Q = 0.98
SETTING = {"aggregation": "top2_mean", "features": v8.V7_FEATURES, "grouped": False, "rules_first": False}


def run(task):
    dataset, data_dir, params, model_seed, dep = task
    feats = v7._dataset(data_dir, "capture")
    start = pd.Timestamp(dep["scored_period"]["start"])
    k = dep["review_list"]["k"]
    rules = METHODS["rules"]()
    days_out, weeks_out = [], []
    for sub_county, rows in feats.groupby("sub_county"):
        rows = rows.sort_values(["date", "school_id"])
        follow_up = set()
        model, next_refit, threshold, refit_day, window_days = None, None, None, None, None
        for week, week_rows in rows[(rows.date >= start) & (rows.date <= END_2025)].groupby("week", sort=True):
            first_day = int(week_rows.day_index.min())
            if model is None or first_day >= next_refit:
                history = rows[(rows.day_index < first_day) & (rows.day_index >= first_day - dep["window_school_days"])]
                history = history[[(s, w) not in follow_up for s, w in zip(history.school_id, history.week)]]
                if history.day_index.nunique() < dep["min_history_school_days"]:
                    model = None
                else:
                    model = v8.make_model(SETTING, params, model_seed, {}).fit(history)
                    next_refit, refit_day = first_day + dep["refit_every_school_days"], first_day
                    hist_days = model.score(history)
                    hist = weekly_scores(history.assign(score=hist_days))
                    threshold = float(hist.quantile(Q))
                    window_days = {"p90_day": float(np.quantile(hist_days, 0.90)), "hist_weeks": np.sort(hist.to_numpy())}
            if model is None:
                continue
            day_scores = model.score(week_rows)
            w = week_rows.assign(score=day_scores)
            score = weekly_scores(w).droplevel("week")
            rule_week = week_rows.assign(score=rules.score(week_rows)).groupby("school_id").score.max()
            ranked = score.sort_values(ascending=False)
            listed = [s for s in ranked.index if ranked[s] > threshold][:k]
            labels = week_rows.groupby("school_id").label.agg(lambda s: sorted(set(s) - {""}))
            for row in w.itertuples():
                days_out.append({"dataset": dataset, "model_seed": model_seed, "sub_county": sub_county, "week": week,
                                 "school_id": row.school_id, "date": row.date, "score": row.score, "label": row.label,
                                 "p90_day": window_days["p90_day"]})
            for rank, school in enumerate(ranked.index, 1):
                types = labels[school]
                weeks_out.append({
                    "dataset": dataset, "model_seed": model_seed, "sub_county": sub_county, "week": week, "school_id": school,
                    "score": float(ranked[school]), "rank": rank, "threshold": threshold, "listed": school in listed,
                    "rule_breach": bool(rule_week[school] > 0), "anomalous": bool(types), "types": "|".join(types),
                    "anomalous_days": int((week_rows[week_rows.school_id == school].label != "").sum()),
                    "school_days": int((week_rows.school_id == school).sum()),
                    "percentile_in_window": float(np.searchsorted(window_days["hist_weeks"], ranked[school]) / len(window_days["hist_weeks"])),
                    "refit_day": refit_day,
                })
                if school in listed and types and dep["exclude_follow_up_from_training"]:
                    follow_up.add((school, week))
    return pd.DataFrame(days_out), pd.DataFrame(weeks_out)


def main():
    dep_plan = yaml.safe_load(open(v7.PLAN, encoding="utf-8"))
    dep = dep_plan["deployment"]
    params = json.load(open(v7.EVALUATION, encoding="utf-8"))["results"][v8.METHOD]["params"]
    base = yaml.safe_load(open(FORECASTING_DIR.parent / dep_plan["datasets"]["main"], encoding="utf-8"))
    datasets = {"main": MAIN_DATA}
    for seed in dep_plan["datasets"]["seeds"]:
        out = v7.DATA_ROOT / f"seed_{seed}"
        generate(dict(copy.deepcopy(base), seed=seed), out, quiet=True)
        datasets[f"seed_{seed}"] = out
    tasks = [(name, str(d), params, s, dep) for name, d in datasets.items() for s in dep_plan["model_seeds"]]
    workers = int(os.environ.get("WORKERS", "6"))
    with ProcessPoolExecutor(max_workers=workers) as pool:
        results = list(pool.map(run, tasks))
    OUT.mkdir(parents=True, exist_ok=True)
    days = pd.concat([d for d, _ in results], ignore_index=True)
    weeks = pd.concat([w for _, w in results], ignore_index=True)
    days.to_csv(OUT / "days_2025.csv.gz", index=False)
    weeks.to_csv(OUT / "weeks_2025.csv.gz", index=False)
    print(f"{len(days)} school-days, {len(weeks)} school-weeks; listed {int(weeks.listed.sum())}, "
          f"problem school-weeks {int(weeks.anomalous.sum())}")


if __name__ == "__main__":
    main()
