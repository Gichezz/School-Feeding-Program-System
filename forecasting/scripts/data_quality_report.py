"""
Phase 9 - Step 4: data-quality assessment of the synthetic dataset.

Summarises the generated data and compares it with the configured assumptions
(and, where meaningful, with the US reference data). This is an assessment of
internal consistency and adherence to the simulation assumptions - NOT a
measure of real-world accuracy.

Usage
  python forecasting/scripts/data_quality_report.py
"""

import numpy as np
import pandas as pd

from common import (
    CONFIG_PATH,
    QUALITY_MD,
    SYNTHETIC_DATASET,
    US_REFERENCE_DAILY,
    US_REFERENCE_PROFILE,
    load_config,
    md_table,
    read_json,
)
from generate_synthetic_dataset import DOW_NAMES, load_dataset, resolve_reference_values

MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def pct(x, d=1):
    return f"{100 * x:.{d}f}%"


def describe_row(name, s, d=0):
    s = s.astype(float)
    q = s.quantile([0.05, 0.25, 0.5, 0.75, 0.95])
    vals = [s.min(), q[0.05], q[0.25], q[0.5], q[0.75], q[0.95], s.max()]
    return [name, f"{s.mean():.1f}", f"{s.std():.1f}"] + [f"{v:.{d}f}" for v in vals]


DESC_HEAD = ["Field", "Mean", "SD", "Min", "P5", "P25", "Median", "P75", "P95", "Max"]


def main():
    cfg = load_config(CONFIG_PATH)
    resolve_reference_values(cfg)
    df = load_dataset(SYNTHETIC_DATASET)
    dates = pd.to_datetime(df["date"])
    df["month"] = dates.dt.month
    sd = df[df["is_school_day"]].copy()
    sd["rate"] = sd["students_present"].astype(float) / sd["students_enrolled"].astype(float)
    a = cfg["attendance"]
    L = []

    L.append("# Synthetic Dataset - Data-Quality Report\n")
    L.append("Generated by `forecasting/scripts/data_quality_report.py` from "
             "`forecasting/data/processed/synthetic_kenya_school_daily.csv`.\n")
    L.append("> **Scope.** This report assesses internal consistency and adherence to the configured simulation "
             "assumptions for **one simulated Kenyan school**. It is **not** a measure of real-world accuracy: "
             "no generated value has been compared with observed Kenyan school records.\n")

    # 1. Overview ------------------------------------------------------------
    n_sd = len(sd)
    L.append("## 1. Overview\n")
    L.append(md_table([
        ["Total records", f"{len(df):,}"],
        ["Date range", f"{df['date'].iloc[0]} to {df['date'].iloc[-1]} ({df['school_year'].nunique()} school years)"],
        ["School days", f"{n_sd:,}"],
        ["School-holiday days (inter-term, half-term or public holiday)", f"{int(df['is_school_holiday'].sum()):,}"],
        ["  of which inter-term holiday days", f"{int((df['term'] == 'holiday').sum()):,}"],
        ["  of which half-term days", f"{int(df['is_half_term'].sum()):,}"],
        ["  of which public holidays", f"{int(df['is_public_holiday'].sum()):,}"],
        ["In-term weekend days (neither school day nor holiday)",
         f"{int((~df['is_school_day'] & ~df['is_school_holiday']).sum()):,}"],
        ["Exam-period school days", f"{int(df['is_exam_period'].sum()):,}"],
        ["Special-event days", f"{int(df['is_special_event'].sum()):,}"],
        ["Terms", f"{df.loc[df['term'] != 'holiday', 'term'].nunique()}"],
        ["School days per year (min / mean / max)",
         "{:.0f} / {:.1f} / {:.0f}".format(*sd.groupby('school_year').size().agg(['min', 'mean', 'max']))],
        ["Synthetic records", f"{int((df['source_type'] == 'synthetic').sum()):,}"],
        ["Original or transformed records in this file", f"{int(df['source_type'].isin(['original', 'transformed']).sum())}"],
        ["Duplicate dates", f"{int(df['date'].duplicated().sum())}"],
    ], ["Measure", "Value"]))
    if US_REFERENCE_DAILY.exists():
        us = pd.read_csv(US_REFERENCE_DAILY)
        L.append(f"\nThe US reference data is kept in a separate file (`us_reference_daily.csv`, {len(us)} "
                 "records labelled `transformed`). It is not merged into the synthetic dataset.\n")

    # 2. Missing values -------------------------------------------------------
    L.append("## 2. Missing values\n")
    L.append("Attendance and meal fields are intentionally null on non-school days (no session took place); "
             "they are not filled with zero. `week_of_term` is null outside term; `special_event_type` is null "
             "when there is no event.\n")
    rows = []
    for c in df.columns.drop("month"):
        n = int(df[c].isna().sum())
        if n:
            n_sd_null = int(sd[c].isna().sum()) if c in sd else 0
            rows.append([c, f"{n:,}", pct(n / len(df)), n_sd_null])
    L.append(md_table(rows, ["Field", "Nulls", "Share of records", "Nulls on school days"]))
    L.append("\nAll other fields have no nulls.\n")

    # 3. Attendance -------------------------------------------------------------
    L.append("## 3. Attendance (school days)\n")
    L.append(md_table([describe_row("students_enrolled", sd["students_enrolled"]),
                       describe_row("students_present", sd["students_present"])], DESC_HEAD))
    q = sd["rate"].quantile([0.05, 0.5, 0.95])
    L.append(f"\nAttendance rate (present / enrolled): mean {sd['rate'].mean():.3f}, SD {sd['rate'].std():.3f}, "
             f"P5 {q[0.05]:.3f}, median {q[0.5]:.3f}, P95 {q[0.95]:.3f}, min {sd['rate'].min():.3f}, "
             f"max {sd['rate'].max():.3f}. Configured base rate: {a['base_rate']}.\n")

    def by(col, order=None, label=None):
        g = sd.groupby(col)["rate"].agg(["mean", "count"])
        if order is not None:
            g = g.reindex([o for o in order if o in g.index])
        return md_table([[k, f"{v['mean']:.3f}", int(v["count"])] for k, v in g.iterrows()],
                        [label or col, "Mean rate", "School days"])

    L.append("### By weekday\n")
    dow = a["dow_logit_offsets"]
    g = sd.groupby("day_of_week")["rate"].mean().reindex(DOW_NAMES[:5])
    L.append(md_table([[d, f"{g[d]:.3f}", dow.get(d, 0.0)] for d in DOW_NAMES[:5]],
                      ["Weekday", "Mean rate", "Configured logit offset"]))
    L.append("\n### By calendar position\n")
    sd["position"] = np.select(
        [sd["term"] != sd["term"].shift(1), sd["week_of_term"] == 1, sd["is_exam_period"]],
        ["first day of term", "rest of week 1", "exam period"], "other term days")
    L.append(by("position", ["first day of term", "rest of week 1", "exam period", "other term days"], "Position"))
    L.append("\n### By weather category\n")
    L.append(by("weather_category", [c["name"] for c in cfg["weather_categories"]], "Weather"))
    heavy = sd[sd["weather_category"] == "heavy_rain"]
    base = sd[sd["weather_category"] == "dry"]["rate"].median()
    if len(heavy):
        L.append(f"\n{pct((heavy['rate'] >= base).mean())} of heavy-rain school days still have attendance at or "
                 "above the dry-day median, so rainfall does not deterministically reduce attendance.\n")
    L.append("### By special event\n")
    sd["event"] = sd["special_event_type"].fillna("none")
    L.append(by("event", ["none"] + cfg["special_events"]["types"], "Event"))
    L.append("\n### By term\n")
    sd["term_name"] = sd["term"].str[-2:]
    L.append(by("term_name", label="Term"))

    # 4. Meals ------------------------------------------------------------------
    L.append("\n## 4. Meal planning, preparation and serving (school days)\n")
    L.append(md_table([describe_row(c, sd[c]) for c in
                       ("meals_planned", "meals_prepared", "meals_served", "estimated_meal_demand")], DESC_HEAD))
    plan_err = sd["meals_planned"].astype(float) - sd["estimated_meal_demand"].astype(float)
    prep_ratio = sd["meals_prepared"].astype(float) / sd["meals_planned"].astype(float)
    unmet = sd["estimated_meal_demand"] > sd["meals_prepared"]
    leftover = sd["meals_prepared"].astype(float) - sd["meals_served"].astype(float)
    rainy = set(cfg["rainfall"]["long_rains_months"]) | set(cfg["rainfall"]["short_rains_months"])
    in_rainy = sd["month"].isin(rainy)
    p = cfg["meals"]["preparation"]
    L.append("")
    L.append(md_table([
        ["Planned minus demand (mean / SD)", f"{plan_err.mean():.1f} / {plan_err.std():.1f} meals"],
        ["Days planned below demand", f"{int((plan_err < 0).sum())} ({pct((plan_err < 0).mean())})"],
        ["Prepared / planned on non-shortfall days (mean / SD)",
         f"{prep_ratio[~sd['is_supply_shortfall']].mean():.4f} / {prep_ratio[~sd['is_supply_shortfall']].std():.4f}"],
        ["Supply-shortfall days", f"{int(sd['is_supply_shortfall'].sum())} ({pct(sd['is_supply_shortfall'].mean())})"],
        ["Shortfall rate, rainy-season months (configured)",
         f"{pct(sd.loc[in_rainy, 'is_supply_shortfall'].mean())} "
         f"({pct(p['shortfall_probability'] * p['shortfall_rainy_month_multiplier'])})"],
        ["Shortfall rate, other months (configured)",
         f"{pct(sd.loc[~in_rainy, 'is_supply_shortfall'].mean())} ({pct(p['shortfall_probability'])})"],
        ["Days where demand exceeded meals prepared", f"{int(unmet.sum())} ({pct(unmet.mean())})"],
        ["Prepared minus served (mean / max)", f"{leftover.mean():.1f} / {leftover.max():.0f} meals"],
        ["Demand / present (mean); configured uptake",
         f"{(sd['estimated_meal_demand'].astype(float) / sd['students_present'].astype(float)).mean():.3f}; "
         f"{cfg['meals']['uptake']['base_rate']}"],
        ["Correlation planned vs demand", f"{np.corrcoef(sd['meals_planned'].astype(float), sd['estimated_meal_demand'].astype(float))[0, 1]:.3f}"],
    ], ["Measure", "Value"]))
    L.append("\nThe difference between meals prepared and meals served is **not** classified as food waste. "
             "In this simulation it arises from planning buffers and students who were present but did not take "
             "a meal; in a real school it could also reflect staff meals, second servings, or recording differences.\n")

    # 5. Rainfall ---------------------------------------------------------------
    L.append("## 5. Rainfall (all days)\n")
    L.append(md_table([describe_row("rainfall_mm (all days)", df["rainfall_mm"], 1),
                       describe_row("rainfall_mm (wet days)", df.loc[df["rainfall_mm"] > 0, "rainfall_mm"], 1)],
                      DESC_HEAD))
    r = cfg["rainfall"]
    rows = []
    for m in range(1, 13):
        x = df[df["month"] == m]["rainfall_mm"]
        rows.append([MONTHS[m - 1], f"{(x > 0).mean():.2f}", r["monthly_wet_day_probability"][m - 1],
                     f"{x[x > 0].mean():.1f}", r["monthly_mean_wet_day_mm"][m - 1],
                     f"{x.sum() / df['school_year'].nunique():.0f}"])
    L.append("\n" + md_table(rows, ["Month", "Wet-day share", "Configured", "Mean wet-day mm", "Configured",
                                    "Mean monthly total mm"]))
    annual = df.groupby("school_year")["rainfall_mm"].sum()
    L.append(f"\nAnnual totals: mean {annual.mean():.0f} mm, min {annual.min():.0f} mm, max {annual.max():.0f} mm. "
             "Configured wet-day shares apply before the year-to-year season multiplier, so small differences are expected.\n")
    wc = df["weather_category"].value_counts()
    L.append("Weather categories (all days): " + ", ".join(f"{k} {v:,}" for k, v in wc.items()) + ".\n")

    # 6. Enrollment -------------------------------------------------------------
    L.append("## 6. Enrollment over time\n")
    ey = df.groupby("school_year")["students_enrolled"].agg(["first", "last"])
    ch = (df["students_enrolled"].astype(float).diff().abs() / df["students_enrolled"].astype(float).shift(1)).dropna()
    L.append(f"Enrollment moves from {int(ey['first'].iloc[0])} ({ey.index[0]}) to {int(ey['last'].iloc[-1])} "
             f"({ey.index[-1]}). It changes on {int((ch > 0).sum()):,} of {len(ch):,} days; the largest single-day "
             f"change is {pct(ch.max(), 2)} (configured limit {pct(cfg['enrollment']['max_daily_change_fraction'], 0)}).\n")
    yrs = list(ey.index[::4]) + ([ey.index[-1]] if ey.index[-1] not in ey.index[::4] else [])
    L.append(md_table([[y, int(ey.loc[y, "first"]), int(ey.loc[y, "last"])] for y in yrs],
                      ["Year", "1 Jan", "31 Dec"]))

    # 7. Relationships ----------------------------------------------------------
    L.append("\n## 7. Relationships between variables (school days)\n")
    ar1 = sd["rate"].autocorr(1)
    L.append(md_table([
        ["Correlation rainfall_mm vs attendance rate", f"{np.corrcoef(sd['rainfall_mm'], sd['rate'])[0, 1]:.3f}"],
        ["Lag-1 autocorrelation of attendance rate (consecutive school days)", f"{ar1:.3f}"],
        ["Correlation students_present vs estimated_meal_demand",
         f"{np.corrcoef(sd['students_present'].astype(float), sd['estimated_meal_demand'].astype(float))[0, 1]:.3f}"],
        ["Correlation students_enrolled vs students_present",
         f"{np.corrcoef(sd['students_enrolled'].astype(float), sd['students_present'].astype(float))[0, 1]:.3f}"],
        ["Mean events per term (configured)",
         f"{sd['is_special_event'].sum() / sd['term'].nunique():.2f} ({cfg['special_events']['mean_events_per_term']})"],
    ], ["Relationship", "Value"]))

    # 8. Comparison with US reference -------------------------------------------
    if US_REFERENCE_PROFILE.exists():
        prof = read_json(US_REFERENCE_PROFILE)
        L.append("\n## 8. Comparison with the US reference data\n")
        L.append("Differences below are expected: the synthetic school uses Kenyan-context assumptions and is a "
                 "single school, whereas the US figures summarise ~1,580 New York City-style schools in 2018-19.\n")
        us = pd.read_csv(US_REFERENCE_DAILY)
        us_good = us[~us["is_low_coverage"]]
        L.append(md_table([
            ["Mean school-day attendance rate", f"{sd['rate'].mean():.3f}", f"{prof['mean_attendance_rate']:.3f} (per school-day)",
             "Synthetic base rate is a configured Kenyan assumption, not the US value"],
            ["SD of daily attendance rate", f"{sd['rate'].std():.3f}",
             f"{us_good['attendance_rate'].std():.3f} (all-school daily aggregate)",
             "Different units: one school vs a district aggregate"],
            ["Lowest weekday", sd.groupby('day_of_week')['rate'].mean().idxmin(),
             min(prof["dow_logit_offsets"], key=prof["dow_logit_offsets"].get),
             "Weekday offsets reused from US reference (config: us_reference)"],
            ["Records per year", f"{len(df) / df['school_year'].nunique():.0f} (calendar days)",
             f"{len(us)} (school days only)", "Synthetic file includes non-school days"],
            ["Meal, weather, event fields", "Generated", "Not present", "Only available synthetically"],
        ], ["Measure", "Synthetic", "US reference", "Note"]))

    # 9. Assessment -------------------------------------------------------------
    L.append("\n## 9. Assessment against configured assumptions\n")
    L.append("Each row is computed from the data; 'Consistent' means the generated data moves in the direction "
             "(or lies in the range) the configuration specifies.\n")
    mean_by = lambda col: sd.groupby(col)["rate"].mean()
    pos = mean_by("position")
    wx = mean_by("weather_category")
    evm = mean_by("event")
    wkd = mean_by("day_of_week")
    monthly_mm = df.groupby("month")["rainfall_mm"].mean()
    sf_obs, sf_cfg = sd["is_supply_shortfall"].mean(), p["shortfall_probability"]
    checks = [
        ("First day of term below other term days", pos["first day of term"] < pos["other term days"]),
        ("Exam-period attendance above other term days", pos["exam period"] > pos["other term days"]),
        ("Lowest weekday matches lowest configured offset", wkd.idxmin() == min(dow, key=dow.get)),
        ("Heavy-rain days below dry days on average", wx.get("heavy_rain", np.inf) < wx["dry"]),
        ("Rain effect not deterministic (some heavy-rain days >= dry median)",
         len(heavy) > 0 and (heavy["rate"] >= base).any()),
        ("School-meeting days below no-event days", evm.get("school_meeting", np.inf) < evm["none"]),
        ("Sports days above no-event days", evm.get("sports_day", -np.inf) > evm["none"]),
        ("Wettest months fall in long and short rains",
         set(monthly_mm.nlargest(2).index) <= rainy),
        ("Shortfall rate within +/-1 percentage point of configured base-to-rainy range",
         sf_cfg - 0.01 <= sf_obs <= sf_cfg * p["shortfall_rainy_month_multiplier"] + 0.01),
        ("Mean attendance within 3 points of configured base rate", abs(sd["rate"].mean() - a["base_rate"]) < 0.03),
        ("Enrollment trend positive over the period", ey["last"].iloc[-1] > ey["first"].iloc[0]),
    ]
    L.append(md_table([[name, "Consistent" if ok else "NOT consistent"] for name, ok in checks],
                      ["Assumption", "Result"]))
    L.append("\n**Limitations.** Every relationship above was written into the generator. A forecasting model "
             "trained on this data can at best rediscover these assumptions; good performance on it does not "
             "demonstrate real-world forecasting accuracy.\n")

    QUALITY_MD.write_text("\n".join(L), encoding="utf-8")
    print(f"  wrote {QUALITY_MD}")


if __name__ == "__main__":
    main()
